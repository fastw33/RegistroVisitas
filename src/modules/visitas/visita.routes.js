const router = require('express').Router()
const roles = require('../../middlewares/roles.middleware')
const controller = require('./visita.controller')
const validator = require('./visita.validator')
router.get('/', validator.list, controller.getAll)
router.get('/resumen', controller.summary)
router.post('/', roles('admin', 'recepcion'), validator.create, controller.create)
router.post('/entrada', roles('admin', 'recepcion'), validator.fromAppointment, controller.enterAppointment)
router.post('/ingreso-directo', roles('admin', 'recepcion'), validator.directEntry, controller.enterDirect)
router.get('/:id', validator.get, controller.getById)
router.post('/:id/autorizar', roles('admin', 'anfitrion'), validator.action, controller.authorize(true))
router.post('/:id/rechazar', roles('admin', 'anfitrion'), validator.action, controller.authorize(false))
router.post('/:id/entrada', roles('admin', 'recepcion'), validator.entry, controller.enter)
router.post('/:id/salida', roles('admin', 'recepcion'), validator.get, controller.exit)
module.exports = router
