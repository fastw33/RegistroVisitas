const router = require('express').Router()
const roles = require('../../middlewares/roles.middleware')
const controller = require('./cita.controller')
const validator = require('./cita.validator')
router.get('/', validator.list, controller.getAll)
router.post('/', validator.create, controller.create)
router.post('/validar-pase', roles('admin', 'recepcion'), validator.validatePass, controller.resolvePass)
router.get('/:id', validator.get, controller.getById)
router.post('/:id/aprobar', roles('admin', 'anfitrion'), validator.action, controller.action('aprobar'))
router.post('/:id/cancelar', roles('admin', 'anfitrion'), validator.action, controller.action('cancelar'))
router.post('/:id/no-asistio', roles('admin', 'recepcion', 'anfitrion'), validator.action, controller.action('no-asistio'))
router.patch('/:id/reprogramar', validator.reschedule, controller.action('reprogramar'))
router.post('/:id/pase', validator.get, controller.issuePass)
module.exports = router
