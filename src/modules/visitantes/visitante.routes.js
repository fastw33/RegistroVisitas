const router = require('express').Router()
const roles = require('../../middlewares/roles.middleware')
const controller = require('./visitante.controller')
const validator = require('./visitante.validator')
router.post('/', validator.create, controller.create)
router.get('/identidad', validator.identity, controller.identity)
router.use(roles('admin', 'recepcion'))
router.get('/', validator.list, controller.getAll)
router.get('/:id/historial', require('../../utils/validators').finish([require('../../utils/validators').id(), ...require('../../utils/validators').page]), controller.historial)
router.get('/:id', validator.get, controller.getById)
router.patch('/:id', validator.update, controller.update)
router.patch('/:id/datos-documento', validator.document, controller.saveDocument)
router.post('/:id/correcciones', roles('admin'), validator.correct, controller.correct)
router.get('/:id/correcciones', roles('admin'), validator.corrections, controller.corrections)
module.exports = router
